#!/usr/bin/env python
"""Write the rubric prompts to ``prompts/<rubric>.txt`` (general, tempo, key, instrument).

The prompts are generated by the same code the raters call
(``rewards/rubric.py``), with the literal placeholder ``<MUSIC_DESCRIPTION>`` in
place of the text prompt of the clip being rated. ``--check`` verifies that the
files in ``prompts/`` are up to date.

``prompts/dpo.txt`` (the prompt used to rate the DPO candidates) is not
generated from a rubric and is not written by this script.

    python prompts/render.py           # (re)write prompts/<rubric>.txt
    python prompts/render.py --check   # exit 1 if any file is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

OUT_DIR = REPO_ROOT / "prompts"
PLACEHOLDER = "<MUSIC_DESCRIPTION>"
RUBRICS = ("general", "tempo", "key", "instrument")


def _section(title: str, body: str) -> str:
    rule = "=" * 78
    return f"{rule}\n{title}\n{rule}\n{body.rstrip()}\n"


def render_rubric(name: str) -> str:
    from rewards.rubric import load_rubric

    rubric = load_rubric(name)
    parts = [
        f"Rating prompts for the {name} rubric (rubrics/{name}.yaml).\n"
        "Joint prompting: one call with the joint system prompt and the joint user\n"
        "prompt. Per-dimension prompting: one fresh call per dimension with the\n"
        "per-dimension system prompt. Raters without a system role receive the\n"
        "system prompt prepended to the user turn.\n"
    ]
    parts.append(_section("system prompt (joint)", rubric.qwen_system_prompt()))
    parts.append(_section("system prompt (per-dimension)", rubric.flamingo_system_prompt()))
    parts.append(_section("user prompt (joint)", rubric.qwen_user_prompt(PLACEHOLDER)))
    for key in rubric.keys:
        parts.append(_section(f"user prompt (per-dimension): {key}", rubric.flamingo_dimension_prompt(key, PLACEHOLDER)))
    return "\n".join(parts)


def render_all() -> dict[str, str]:
    return {f"{name}.txt": render_rubric(name) for name in RUBRICS}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = render_all()
    if args.check:
        stale = [n for n, text in files.items() if not (OUT_DIR / n).exists() or (OUT_DIR / n).read_text(encoding="utf-8") != text]
        if stale:
            raise SystemExit(f"stale prompt files: {stale}")
        print("prompt files are up to date")
        return
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        print(f"wrote {OUT_DIR / name}")


if __name__ == "__main__":
    main()
